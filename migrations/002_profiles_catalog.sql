-- Profiles, visibility, published projects and certificates.
CREATE TABLE IF NOT EXISTS profiles (
  id SERIAL PRIMARY KEY,
  user_id INTEGER UNIQUE NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  bio TEXT NOT NULL DEFAULT '',
  photo_url VARCHAR(500),
  city VARCHAR(120),
  country VARCHAR(120),
  start_date TIMESTAMP,
  cohort_name VARCHAR(120),
  status VARCHAR(32) NOT NULL DEFAULT 'learning',
  level VARCHAR(64) NOT NULL DEFAULT 'начинающий',
  interests TEXT NOT NULL DEFAULT '[]',
  portfolio_url VARCHAR(500),
  completion_percent INTEGER NOT NULL DEFAULT 0,
  final_exam_passed BOOLEAN NOT NULL DEFAULT FALSE,
  publish_in_catalog BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS profile_visibility (
  id SERIAL PRIMARY KEY,
  profile_id INTEGER UNIQUE NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  scope VARCHAR(32) NOT NULL DEFAULT 'owner',
  show_projects BOOLEAN NOT NULL DEFAULT FALSE,
  show_certificates BOOLEAN NOT NULL DEFAULT FALSE,
  show_photo BOOLEAN NOT NULL DEFAULT FALSE,
  show_contacts BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS project_publications (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  summary TEXT NOT NULL DEFAULT '',
  url VARCHAR(500),
  status VARCHAR(32) NOT NULL DEFAULT 'completed',
  is_public BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS certificates (
  id SERIAL PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  code VARCHAR(120) UNIQUE NOT NULL,
  issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_public BOOLEAN NOT NULL DEFAULT FALSE
);
